/**
 * The privacy-program PDF's flow map says why systems are missing from it:
 * systems with no flow and no activity ("orphans") are counted apart from
 * systems left out only because they are not in production.
 */
import { describe, expect, it } from "vitest";
import { buildFlowGraphInputs } from "@/server/services/export/privacy-program/flow-input";

describe("buildFlowGraphInputs counts", () => {
  const assets = [
    { id: "web", name: "Web", type: "APPLICATION", isProduction: true },
    { id: "db", name: "DB", type: "DATABASE", isProduction: true },
    { id: "lake", name: "Lake", type: "CLOUD_SERVICE", isProduction: false },
    { id: "paper", name: "Paper", type: "PHYSICAL", isProduction: true },
  ];
  const edges = [
    { sourceAssetId: "web", destinationAssetId: "db", dataCategories: ["IDENTIFIERS"], frequency: "Daily", isAutoGenerated: false },
    { sourceAssetId: "db", destinationAssetId: "lake", dataCategories: ["HEALTH"], frequency: "Monthly", isAutoGenerated: false },
  ];

  it("separates orphans from systems not in production", () => {
    const r = buildFlowGraphInputs(assets, edges, []);
    expect(r.filteredAssetCount).toBe(2);
    expect(r.orphansDropped).toBe(1); // paper
    expect(r.nonProductionDropped).toBe(1); // lake: it has a flow
    expect(r.batches[0]!.edges).toHaveLength(1); // db -> lake left out with lake
  });

  it("keeps systems not in production when asked to", () => {
    const r = buildFlowGraphInputs(assets, edges, [], { productionOnly: false });
    expect(r.nonProductionDropped).toBe(0);
    expect(r.orphansDropped).toBe(1);
    expect(r.batches[0]!.edges).toHaveLength(2);
  });
});
