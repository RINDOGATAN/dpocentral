/**
 * Transfer markers on the data flow map
 * (src/server/services/data-flows/transfer-markers.ts), and generated flows
 * as drafts to confirm (src/server/services/data-flows/auto-flows.ts).
 */

import { describe, it, expect } from "vitest";
import { isOutsideEea, transferMarkers } from "@/server/services/data-flows/transfer-markers";
import { confirmedMetadata, isDraftFlow, takenOverMetadata } from "@/server/services/data-flows/auto-flows";

const assets = [
  { id: "shop", name: "Web Shop", type: "APPLICATION" },
  { id: "mc", name: "Mailchimp", vendor: "Intuit Mailchimp", type: "THIRD_PARTY" },
  { id: "pay", name: "Payments", vendor: null, type: "THIRD_PARTY" },
  { id: "db", name: "Customer DB", type: "DATABASE" },
  { id: "crm", name: "CRM", type: "CLOUD_SERVICE" },
];

describe("isOutsideEea", () => {
  it("treats the EU-27, Iceland, Liechtenstein and Norway as inside", () => {
    for (const c of ["ES", "de", "IE", "IS", "LI", "NO"]) expect(isOutsideEea(c)).toBe(false);
    for (const c of ["US", "GB", "CH", "IN", "jp"]) expect(isOutsideEea(c)).toBe(true);
    expect(isOutsideEea("India")).toBe(false);
    expect(isOutsideEea("")).toBe(false);
  });
});

describe("transferMarkers", () => {
  it("places a transfer on the system named as its receiving organisation (name or vendor)", () => {
    const m = transferMarkers(
      assets,
      [
        { id: "t1", destinationCountry: "US", destinationOrg: "mailchimp " },
        { id: "t2", destinationCountry: "IN", destinationOrg: "Intuit Mailchimp" },
        { id: "t3", destinationCountry: "FR", destinationOrg: "Mailchimp" },
      ],
      new Map()
    );
    expect(m).toEqual([{ assetId: "mc", transferIds: ["t1", "t2"], countries: ["IN", "US"] }]);
  });

  it("falls back to the activity's only external system, never to a guess among several", () => {
    const links = new Map([
      ["a1", ["shop", "db", "pay"]],
      ["a2", ["shop", "pay", "crm"]],
    ]);
    const m = transferMarkers(
      assets,
      [
        { id: "t1", destinationCountry: "US", destinationOrg: "Acquirer Inc", processingActivityId: "a1" },
        { id: "t2", destinationCountry: "US", destinationOrg: "Someone", processingActivityId: "a2" },
      ],
      links
    );
    expect(m).toEqual([{ assetId: "pay", transferIds: ["t1"], countries: ["US"] }]);
  });

  it("ignores inactive transfers", () => {
    expect(
      transferMarkers(assets, [{ id: "t1", destinationCountry: "US", destinationOrg: "CRM", isActive: false }], new Map())
    ).toEqual([]);
  });
});

describe("generated flows as drafts", () => {
  const draft = { autoGenerated: true, activityId: "a1" };
  it("a generated flow is a draft until confirmed or edited", () => {
    expect(isDraftFlow(draft)).toBe(true);
    expect(isDraftFlow(null)).toBe(false);
    expect(isDraftFlow({})).toBe(false);
    expect(isDraftFlow(takenOverMetadata(draft))).toBe(false);
  });

  it("confirming keeps the activity and records who and when", () => {
    const at = new Date("2026-10-12T10:00:00Z");
    expect(confirmedMetadata(draft, "u1", at)).toEqual({
      autoGenerated: false,
      activityId: "a1",
      confirmedFromGenerated: true,
      confirmedBy: "u1",
      confirmedAt: "2026-10-12T10:00:00.000Z",
    });
    expect(isDraftFlow(confirmedMetadata(draft, "u1", at))).toBe(false);
    const own = { note: "x" };
    expect(confirmedMetadata(own, "u1", at)).toBe(own);
  });
});
