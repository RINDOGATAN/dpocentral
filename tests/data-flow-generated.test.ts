/**
 * Generated data flows follow the processing activity's systems: when a system
 * is unlinked, the flows the activity drew to it go; a flow a person edited
 * stays; a pair another activity still needs is drawn again.
 */
import { describe, expect, it } from "vitest";
import {
  chainPairs,
  staleGeneratedFlowIds,
  syncGeneratedFlows,
  takenOverMetadata,
  type ChainAsset,
} from "@/server/services/data-flows/auto-flows";

const A: ChainAsset = { id: "web", name: "Web Shop", type: "APPLICATION" };
const B: ChainAsset = { id: "db", name: "Customer DB", type: "DATABASE" };
const C: ChainAsset = { id: "pay", name: "Payments", type: "THIRD_PARTY" };
const D: ChainAsset = { id: "paper", name: "Paper Archive", type: "PHYSICAL" };

describe("chainPairs", () => {
  it("orders systems by pipeline rank and pairs neighbours", () => {
    expect(chainPairs([C, A, D, B]).map(([s, d]) => `${s.id}>${d.id}`)).toEqual(["web>db", "db>pay", "pay>paper"]);
  });
  it("has no pair for fewer than two systems", () => {
    expect(chainPairs([A])).toEqual([]);
  });
});

describe("staleGeneratedFlowIds", () => {
  const gen = (id: string, s: string, d: string, activityId = "act") => ({
    id,
    sourceAssetId: s,
    destinationAssetId: d,
    metadata: { autoGenerated: true, activityId },
  });
  const flows = [
    gen("f1", "web", "db"),
    gen("f2", "db", "pay"),
    gen("f3", "pay", "paper"),
    gen("f4", "db", "pay", "other"),
    { id: "f5", sourceAssetId: "pay", destinationAssetId: "paper", metadata: null },
    { id: "f6", sourceAssetId: "db", destinationAssetId: "pay", metadata: { autoGenerated: false, activityId: "act" } },
  ];
  it("keeps the activity's flows that still join a pair", () => {
    expect(staleGeneratedFlowIds(flows, "act", chainPairs([A, B, C, D]))).toEqual([]);
  });
  it("marks the flows to systems the activity no longer links", () => {
    expect(staleGeneratedFlowIds(flows, "act", chainPairs([A, B]))).toEqual(["f2", "f3"]);
  });
  it("marks every flow of a deleted activity, and only its own", () => {
    expect(staleGeneratedFlowIds(flows, "act", [])).toEqual(["f1", "f2", "f3"]);
  });
});

describe("takenOverMetadata", () => {
  it("turns a generated flow into one the person owns", () => {
    expect(takenOverMetadata({ autoGenerated: true, activityId: "act" })).toEqual({
      autoGenerated: false,
      activityId: "act",
      editedFromGenerated: true,
    });
  });
  it("leaves other flows alone", () => {
    expect(takenOverMetadata(null)).toBeNull();
    const m = { source: "quickstart" };
    expect(takenOverMetadata(m)).toBe(m);
  });
});

// ── syncGeneratedFlows over a small in-memory store ─────────────────────
type Flow = { id: string; organizationId: string; sourceAssetId: string; destinationAssetId: string; metadata: unknown };

function store(links: Record<string, ChainAsset[]>, flows: Flow[]) {
  let n = 0;
  const activity = (id: string) =>
    links[id] ? { id, name: id, categories: ["IDENTIFIERS"], assets: links[id]!.map((a) => ({ dataAsset: a })) } : null;
  return {
    flows,
    processingActivity: {
      findFirst: async ({ where }: { where: { id: string } }) => activity(where.id),
      findMany: async ({ where }: { where: { AND?: Array<{ assets: { some: { dataAssetId: string } } }> } }) =>
        Object.keys(links)
          .filter((id) => (where.AND ?? []).every((c) => links[id]!.some((a) => a.id === c.assets.some.dataAssetId)))
          .map((id) => ({ id })),
    },
    dataFlow: {
      findMany: async ({ where }: { where: { metadata?: unknown } }) =>
        where.metadata
          ? flows.filter((f) => (f.metadata as { autoGenerated?: boolean } | null)?.autoGenerated === true)
          : flows,
      deleteMany: async ({ where }: { where: { id: { in: string[] } } }) => {
        const before = flows.length;
        for (const id of where.id.in) {
          const i = flows.findIndex((f) => f.id === id);
          if (i >= 0) flows.splice(i, 1);
        }
        return { count: before - flows.length };
      },
      create: async ({ data }: { data: Omit<Flow, "id"> }) => {
        const row = { ...data, id: `new${++n}` };
        flows.push(row);
        return row;
      },
    },
  };
}

const pairsOf = (flows: Flow[]) => flows.map((f) => `${f.sourceAssetId}>${f.destinationAssetId}`).sort();

describe("syncGeneratedFlows", () => {
  it("removes the flows to unlinked systems and draws the new pair", async () => {
    const links: Record<string, ChainAsset[]> = { act: [A, B, C, D] };
    const db = store(links, []);
    await syncGeneratedFlows(db, "o1", ["act"]);
    expect(pairsOf(db.flows)).toEqual(["db>pay", "pay>paper", "web>db"]);

    links.act = [A, B, D]; // Payments unlinked
    const r = await syncGeneratedFlows(db, "o1", ["act"]);
    expect(r.removed).toBe(2);
    expect(pairsOf(db.flows)).toEqual(["db>paper", "web>db"]);
  });

  it("keeps a generated flow someone edited", async () => {
    const links: Record<string, ChainAsset[]> = { act: [A, B] };
    const db = store(links, [
      { id: "mine", organizationId: "o1", sourceAssetId: "web", destinationAssetId: "db", metadata: { autoGenerated: false, activityId: "act", editedFromGenerated: true } },
    ]);
    links.act = [A];
    await syncGeneratedFlows(db, "o1", ["act"]);
    expect(db.flows.map((f) => f.id)).toEqual(["mine"]);
  });

  it("redraws a pair another activity still needs", async () => {
    const links: Record<string, ChainAsset[]> = { act: [A, B], other: [A, B] };
    const db = store(links, []);
    await syncGeneratedFlows(db, "o1", ["act", "other"]);
    expect(db.flows).toHaveLength(1); // deduped: one flow serves both
    links.act = [A]; // the activity that drew it lets go
    await syncGeneratedFlows(db, "o1", ["act"]);
    expect(pairsOf(db.flows)).toEqual(["web>db"]);
    expect((db.flows[0]!.metadata as { activityId: string }).activityId).toBe("other");
  });

  it("removes every generated flow of a deleted activity", async () => {
    const links: Record<string, ChainAsset[]> = { act: [A, B, C] };
    const db = store(links, []);
    await syncGeneratedFlows(db, "o1", ["act"]);
    delete links.act;
    await syncGeneratedFlows(db, "o1", ["act"]);
    expect(db.flows).toEqual([]);
  });
});
