const read = (path: string) => readFileSync(path, "utf8");
const statuses = (over: Partial<PathCounts>) => evaluatePath(DPO_CENTRAL_PATH, { ...EMPTY_PATH_COUNTS, ...over });

describe("honest progress", () => {
  it("one bare record never marks its step done", () => {
    const s = statuses({ dataAssets: 1, processingActivities: 1, vendors: 1, transfers: 1, jurisdictions: 1 });
    expect(s.dataInventory).toBe("started");
    expect(s.ropa).toBe("started");
    expect(s.vendors).toBe("started");
    expect(s.transfers).toBe("started");
  });

  it("an activity needs data subjects, data categories and retention; recipients may be none", () => {
    expect(missingMinimumFields({ dataSubjects: [], categories: [], recipients: [] })).toEqual([
      "dataSubjects",
      "categories",
      "retention",
    ]);
    expect(
      missingMinimumFields({ dataSubjects: ["Patients"], categories: ["HEALTH"], recipients: [], retentionDays: 3650 }),
    ).toEqual([]);
  });

  it("a vendor needs to be in use, with its data and countries", () => {
    expect(missingVendorFields({ status: "PROSPECTIVE", dataProcessed: [], countries: [] })).toEqual([
      "inUse",
      "dataProcessed",
      "countries",
    ]);
    expect(missingVendorFields({ status: "ACTIVE", dataProcessed: ["IDENTIFIERS"], countries: ["US"] })).toEqual([]);
  });

  it("says what is missing on the record closest to complete", () => {
    expect(closestMissing([["categories", "retention"], ["retention"]])).toEqual(["retention"]);
    expect(closestMissing([])).toEqual([]);
  });

  it("every missing-field key has words in both languages", () => {
    const keys = ["dataSubjects", "categories", "retention", "dataElements", "inUse", "dataProcessed", "countries", "complianceStatus"];
    for (const k of keys) {
      expect((en.guided.band.fields as Record<string, string>)[k], k).toBeTruthy();
      expect((es.guided.band.fields as Record<string, string>)[k], k).toBeTruthy();
    }
  });

  it("rights requests and breaches read 'ready when needed', never as unfinished work", () => {
    const s = statuses({ dsarIntakeConfigured: true, processingActivitiesComplete: 1 });
    expect(s.dsar).toBe("ready");
    expect(s.incidents).toBe("ready");
    expect(isStepMet(s.dsar)).toBe(true);
    expect(en.guided.stepStatus.ready).toBe("ready when needed");
    expect(es.guided.stepStatus.ready).toBe("a punto para cuando haga falta");
    // A logged request alone does not stand in for setting up the intake.
    expect(statuses({ dsarRequests: 1 }).dsar).toBe("started");
  });

  it("quick-start drafts of DPIAs do not make the risk and vendor steps look started", () => {
    // path-counts.ts leaves untouched automatic drafts out of these counts.
    const counts = read("src/server/services/program/path-counts.ts");
    expect(counts).toMatch(/autoGenerated/);
    expect(counts).toMatch(/assessments: Math\.max\(0, assessments - riskAutoDrafts\)/);
    expect(counts).toMatch(/vendorAssessments: Math\.max\(0, vendorAssessments - vendorAutoDrafts\)/);
    // Vendor due diligence counts only vendor assessments, not a DPIA linked to a vendor.
    expect(counts).toMatch(/template: \{ type: "VENDOR" as const \}/);
    const s = statuses({ assessments: 0, vendorAssessments: 0 });
    expect(s.assessments).toBe("todo");
    // Coming while the vendor risk assessment module is announced.
    expect(s.vendorDueDiligence).toBe("coming");
  });

  it("the executive report is not ready after the quick start alone", () => {
    const facts = {
      ...EMPTY_PATH_COUNTS,
      quickstartCompleted: true,
      jurisdictions: 2,
      dataAssets: 9,
      dataAssetsDrafts: 9,
      processingActivities: 7,
      processingActivitiesDrafts: 7,
      activitiesIncomplete: 0,
      dpiaAssessments: 0,
      dpiaApproved: 0,
      dpiaAccess: "available" as const,
      dpaContracts: 0,
      incidentsMissingImpact: 0,
      incidentNotifications: 0,
      aiAssistOn: false,
      dsarCompleted: 0,
    };
    // Set-up is done (one stage) ...
    expect(programFigure(DPO_CENTRAL_PATH, evaluatePath(DPO_CENTRAL_PATH, facts)).confirmed).toBe(1);
    // ... but the report has no content yet: it asks for the drafts to be confirmed.
    const board = evaluateRegister(registerFor({ dsarEnabled: true }), facts).find((d) => d.id === "boardReport")!;
    expect(board.status).toEqual({ state: "needsInput", input: "confirmDrafts" });
  });

  it("the next step after a bare activity is still the record of processing", () => {
    const s = statuses({
      quickstartCompleted: true,
      jurisdictions: 1,
      dataAssets: 1,
      dataAssetsComplete: 1,
      processingActivities: 1,
    });
    expect(nextStep(DPO_CENTRAL_PATH, s)?.step.id).toBe("ropa");
  });

  it("the step band says what finishes the step, and only the stage message is announced", () => {
    const band = read("src/components/guided/step-band.tsx");
    expect(band).toMatch(/band\.missing/);
    expect(band).toMatch(/band\.readyWhenNeeded/);
    expect(band).toMatch(/<p role="status"/);
    expect(band).not.toMatch(/text-sm"\n\s+role="status"/);
  });
});

describe("the Reports page", () => {
  it("shows the number only when every area has data", () => {
    const page = read("src/app/(dashboard)/privacy/reports/page.tsx");
    const value = page.indexOf('data-testid="reports-score-value"');
    const gate = page.lastIndexOf(": fullCoverage ? (", value);
    expect(value).toBeGreaterThan(0);
    expect(gate).toBeGreaterThan(0);
    expect(page).toMatch(/score\.withheld/);
    expect(en.pages.reports.score.withheld).not.toMatch(/\d+ \/ 100/);
  });

  it("lists what raises the score, per area", () => {
    const hints = scoreHints(
      {
        ropa: { score: 60, total: 5, compliant: 3 },
        assessment: { score: null, total: 0, compliant: 0 },
        dsar: { score: null, total: 0, compliant: 0 },
        incident: { score: null, total: 0, compliant: 0 },
        vendor: { score: 100, total: 2, compliant: 2 },
      },
      { dsarOn: true },
    );
    expect(hints.map((h) => [h.area, h.kind, h.count])).toEqual([
      ["ropa", "raise", 2],
      ["dsar", "unrated", 0],
      ["assessment", "unrated", 0],
      ["incident", "unrated", 0],
    ]);
    expect(scoreHints({ dsar: { score: null, total: 0, compliant: 0 } }, { dsarOn: false })).toEqual([]);
    for (const area of ["ropa", "assessment", "dsar", "incident", "vendor"] as const) {
      for (const kind of ["unrated", "raise"] as const) {
        expect(en.pages.reports.raise[area][kind]).toBeTruthy();
        expect(es.pages.reports.raise[area][kind]).toBeTruthy();
      }
    }
  });
});

describe("rights request references", () => {
  it("never shows a raw database id", () => {
    expect(formatRequestRef("cmveqk4yd00tr75hz1xavnxdy", "en")).toBe("REQ-AVNXDY");
    expect(formatRequestRef("cmveqk4yd00tr75hz1xavnxdy", "es")).toBe("SOL-AVNXDY");
    // A readable reference (imports, demos) is kept as it is.
    expect(formatRequestRef("DSAR-2026-0003", "es")).toBe("DSAR-2026-0003");
    for (const file of ["src/app/(dashboard)/privacy/dsar/page.tsx", "src/app/(dashboard)/privacy/dsar/[id]/page.tsx"]) {
      const src = read(file);
      expect(src, file).not.toMatch(/>\{request\.publicId\}</);
      expect(src, file).toMatch(/formatRequestRef\(request\.publicId, locale\)/);
    }
  });

  it("finds a request by the reference a person reads", () => {
    expect(requestRefSearchTail("REQ-AVNXDY")).toBe("AVNXDY");
    expect(requestRefSearchTail(" sol-avnxdy ")).toBe("avnxdy");
    expect(requestRefSearchTail("Jane")).toBeNull();
    expect(read("src/server/routers/privacy/dsar.ts")).toMatch(/requestRefSearchTail\(input\.search\)/);
  });

  it("says how to start when a request has no task yet", () => {
    expect(read("src/app/(dashboard)/privacy/dsar/[id]/page.tsx")).toMatch(/progress\.noTasks/);
  });
});

describe("All clients", () => {
  const now = new Date("2026-10-19T10:00:00Z");

  it("shows a request due in 32 days rather than 'None'", () => {
    const later = { kind: "dsarDue" as const, at: "2026-11-20T00:00:00Z", publicId: "abc123", href: "/privacy/dsar/1" };
    const due = clientDueItems([], [], later);
    expect(nearestDeadline(due)).toEqual(later);
    // Listed once when the 30-day list already has it.
    expect(clientDueItems([later], [], later)).toHaveLength(1);
    expect(en.portfolio.noDeadline).toBe("None in the next 30 days");
    expect(es.portfolio.noDeadline).toBe("Ninguno en los próximos 30 días");
  });

  it("puts a review coming due among the due items", () => {
    const review = {
      kind: "activityReview" as const,
      at: "2026-10-25T00:00:00Z",
      id: "a1",
      name: "Payroll",
      href: "/privacy/data-inventory/activities/a1",
    };
    const request = { kind: "dsarDue" as const, at: "2026-11-20T00:00:00Z", publicId: "abc123", href: "/x" };
    expect(nearestDeadline(clientDueItems([], [review], request))).toEqual(review);
  });

  it("gives each client one status word", () => {
    const base = { confirmedStages: 3, drafts: 0, needsAttention: false, nearest: null, now };
    expect(clientStatus(base)).toBe("onTrack");
    expect(clientStatus({ ...base, drafts: 4 })).toBe("toConfirm");
    expect(clientStatus({ ...base, confirmedStages: 0 })).toBe("setup");
    expect(clientStatus({ ...base, needsAttention: true })).toBe("action");
    expect(
      clientStatus({ ...base, nearest: { kind: "dsarDue", at: "2026-10-01T00:00:00Z", publicId: "x", href: "/" } }),
    ).toBe("action");
    for (const k of ["action", "setup", "toConfirm", "onTrack"] as const) {
      expect(en.portfolio.status[k]).toBeTruthy();
      expect(es.portfolio.status[k]).toBeTruthy();
    }
  });

  it("reads reviews due within 30 days, and the nearest open request however far", async () => {
    const prisma = {
      processingActivity: {
        findMany: vi.fn().mockResolvedValue([{ id: "a1", name: "Payroll", nextReviewAt: new Date("2026-10-30T00:00:00Z") }]),
      },
      vendor: {
        findMany: vi.fn().mockResolvedValue([{ id: "v1", name: "Mailer", nextReviewAt: new Date("2026-10-10T00:00:00Z") }]),
      },
      dSARRequest: {
        findMany: vi.fn().mockResolvedValue([
          { id: "r1", publicId: "p1", dueDate: new Date("2026-12-01T00:00:00Z"), extendedDueDate: null },
          { id: "r2", publicId: "p2", dueDate: new Date("2026-11-01T00:00:00Z"), extendedDueDate: new Date("2027-01-01T00:00:00Z") },
          { id: "r3", publicId: "p3", dueDate: new Date("2026-11-20T00:00:00Z"), extendedDueDate: null },
        ]),
      },
    };
    const reviews = await loadReviewsDue(prisma as never, "org", now);
    expect(reviews.map((r) => r.kind)).toEqual(["vendorReview", "activityReview"]);
    expect(prisma.processingActivity.findMany.mock.calls[0][0].where).toMatchObject({
      organizationId: "org",
      isActive: true,
      nextReviewAt: { lt: new Date("2026-11-18T10:00:00Z") },
    });
    const next = await loadNextRequestDue(prisma as never, "org");
    // The extension counts: r2 is due in January, so r3 (20 November) is the nearest.
    expect(next?.publicId).toBe("p3");
  });

  it("the overview and the firm view both carry the reviews", () => {
    expect(read("src/server/routers/privacy/programPath.ts")).toMatch(/loadReviewsDue\(ctx\.prisma, ctx\.organization\.id\)/);
    expect(read("src/server/routers/privacy/clients.ts")).toMatch(/loadNextRequestDue\(/);
    expect(read("src/components/guided/guided-dashboard.tsx")).toMatch(/deadline-review/);
  });
});

describe("onboarding and language", () => {
  it("applies the account's language only on a browser with no choice of its own", () => {
    expect(localeToApply(null, "es", "en")).toBe("es");
    expect(localeToApply("en", "es", "en")).toBeNull();
    expect(localeToApply(null, "es", "es")).toBeNull();
    expect(localeToApply(null, "fr", "en")).toBeNull();
    expect(localeToApply(null, null, "en")).toBeNull();
  });

  it("the first screen offers the language, and a professional names a client, then lands on All clients", () => {
    const welcome = read("src/components/privacy/onboarding-welcome.tsx");
    expect(welcome).toMatch(/<AccountLanguageSwitcher \/>/);
    expect(welcome).toMatch(/router\.push\("\/privacy\/clients"\)/);
    expect(welcome).toMatch(/t\("clientName"\)/);
    expect(en.onboarding.clientName).toBeTruthy();
    expect(es.onboarding.clientName).toBeTruthy();
  });

  it("the quick-start redirect is remembered per organisation", () => {
    const cookie = quickstartSeenCookie("org_1");
    const header = cookie.split(";")[0];
    expect(hasSeenQuickstart(header, "org_1")).toBe(true);
    expect(hasSeenQuickstart(header, "org_2")).toBe(false);
  });

  it("sign-in returns to the page, never to another site", () => {
    expect(safeCallbackPath("/privacy/dsar/abc?tab=tasks")).toBe("/privacy/dsar/abc?tab=tasks");
    expect(safeCallbackPath("https://evil.example/privacy")).toBe("/privacy");
    expect(safeCallbackPath("//evil.example/privacy")).toBe("/privacy");
    expect(safeCallbackPath("/\\evil.example")).toBe("/privacy");
    expect(safeCallbackPath("/admin")).toBe("/privacy");
    expect(safeCallbackPath(null)).toBe("/privacy");
  });
});

