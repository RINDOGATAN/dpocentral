/**
 * Navigation, progress, onboarding and the consultant view:
 *
 * - honest progress: minimum fields before a step is done, "ready when
 *   needed" for steps that wait for an event, and what is still missing;
 * - the Reports page shows no overall number on partial data, and says what
 *   raises it;
 * - rights requests read by their short reference, also in search;
 * - All clients: the nearest due item (however far), reviews coming due, a
 *   status per client;
 * - the language as an account setting; sign-in returns to the page.
 */

