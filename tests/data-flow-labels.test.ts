/**
 * The data flow map speaks the reader's language: edge labels, category
 * abbreviations and frequencies come from the message bundles, in both
 * languages, and the PDF maps use the same words.
 */
import { describe, expect, it } from "vitest";
import { createTranslator } from "next-intl";
import en from "@/messages/en.json";
import es from "@/messages/es.json";
import { edgeShortLabel, FREQUENCY_LABEL_KEYS, frequencyLabel, isGeneratedFlow, LEGACY_GENERATED_DESCRIPTION } from "@/components/privacy/data-flow/flow-labels";

const CATEGORIES = Object.keys(en.enums.dataCategory);

describe("map words in both languages", () => {
  for (const [lang, messages] of [["en", en], ["es", es]] as const) {
    const abbr = createTranslator({ locale: lang, messages, namespace: "dataFlow.abbr" });
    const freq = createTranslator({ locale: lang, messages, namespace: "dataFlow.frequencyOptions" });
    it(`${lang}: every data category has an abbreviation`, () => {
      for (const c of CATEGORIES) expect(abbr.has(c as never), c).toBe(true);
    });
    it(`${lang}: every frequency the app stores has a label`, () => {
      for (const k of Object.values(FREQUENCY_LABEL_KEYS)) expect(freq.has(k as never), k).toBe(true);
    });
  }

  it("labels an edge in Spanish", () => {
    const abbr = createTranslator({ locale: "es", messages: es, namespace: "dataFlow.abbr" });
    const freq = createTranslator({ locale: "es", messages: es, namespace: "dataFlow.frequencyOptions" });
    const a = (k: string) => abbr(k as never);
    const f = (k: string) => freq(k as never);
    expect(edgeShortLabel(["HEALTH", "DEMOGRAPHICS"], "Monthly", a, f)).toBe("SAL +1 · mensual");
    expect(edgeShortLabel(["BEHAVIORAL"], "Continuous", a, f)).toBe("COM · continua");
    expect(edgeShortLabel(["IDENTIFIERS"], "Diaria", a, f)).toBe("ID · diaria"); // a template's own word
    expect(edgeShortLabel([], null, a, f)).toBeNull();
  });

  it("keeps free-text frequencies as written", () => {
    expect(frequencyLabel("Twice a day", (k) => k)).toBe("Twice a day");
    expect(frequencyLabel(null, (k) => k)).toBeNull();
  });

  it("recognises generated flows, edited or not, and the old stored text", () => {
    expect(isGeneratedFlow({ autoGenerated: true })).toBe(true);
    expect(isGeneratedFlow({ autoGenerated: false, editedFromGenerated: true })).toBe(true);
    expect(isGeneratedFlow({ source: "quickstart" })).toBe(false);
    expect(LEGACY_GENERATED_DESCRIPTION.test('Auto-generated from processing activity "Orders"')).toBe(true);
  });
});

describe("PDF flow map words", () => {
  it("writes the asset type the reader's way under each system", async () => {
    const { buildDotSource } = await import("@/server/services/export/flow-graph-pdf");
    const dot = buildDotSource(
      [{ id: "a", name: "CRM", type: "DATABASE" }, { id: "b", name: "Pagos", type: "THIRD_PARTY" }],
      [{ sourceAssetId: "a", destinationAssetId: "b", label: "Identificadores · Diaria" }],
      { typeLabel: (t) => ({ DATABASE: "Base de datos", THIRD_PARTY: "Tercero" })[t] ?? t }
    );
    expect(dot).toContain("Base de datos");
    expect(dot).toContain("Tercero");
    expect(dot).not.toContain("third party");
    expect(dot).toContain("Identificadores · Diaria");
  });

  it("labels the program map's flows through the given translator", async () => {
    const { buildFlowGraphInputs } = await import("@/server/services/export/privacy-program/flow-input");
    const r = buildFlowGraphInputs(
      [{ id: "a", name: "A", type: "APPLICATION", isProduction: true }, { id: "b", name: "B", type: "DATABASE", isProduction: true }],
      [{ sourceAssetId: "a", destinationAssetId: "b", dataCategories: ["HEALTH"], frequency: "Continuous", isAutoGenerated: true }],
      [],
      {},
      { unassigned: "Sin asignar", overview: "Resumen", moreSuffix: (n) => ` +${n}`, edgeLabel: () => "Datos de salud · Continua" }
    );
    expect(r.batches[0]!.edges[0]!.label).toBe("Datos de salud · Continua");
  });
});
