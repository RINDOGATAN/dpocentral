import type { DataAssetType } from "@prisma/client";
import ELK from "elkjs/lib/elk.bundled.js";
import { classifyCategories, sensitivityRank } from "./flow-palette";

const elk = new ELK();

export interface FlowData {
  id: string;
  name: string;
  description?: string | null;
  sourceAssetId: string;
  destinationAssetId: string;
  dataCategories: string[];
  frequency?: string | null;
  volume?: string | null;
  encryptionMethod?: string | null;
  isAutomated: boolean;
  metadata?: unknown;
  sourceAsset: AssetData;
  destinationAsset: AssetData;
}

export interface AssetData {
  id: string;
  name: string;
  description?: string | null;
  type: DataAssetType;
  owner?: string | null;
  location?: string | null;
  hostingType?: string | null;
  vendor?: string | null;
  isProduction: boolean;
  /** Transfers outside the EEA placed on this system (map marker). */
  transfersOutsideEea?: TransferMarkerData | null;
}

export type TransferStatus = "COMPLIANT" | "NEEDS_REVIEW" | "NON_COMPLIANT" | "PENDING";

/** A system's transfers outside the EEA, with each one's safeguard and status. */
export interface TransferMarkerData {
  transferIds: string[];
  countries: string[];
  transfers?: { id: string; country: string; mechanism: string | null; status: TransferStatus; suggested?: boolean }[];
  worstStatus?: TransferStatus;
  /** Vendor countries outside the EEA with no transfer record on this system. */
  unrecordedCountries?: string[];
}

export interface AssetNodeData extends Record<string, unknown> {
  label: string;
  asset: AssetData;
  incomingFlows: number;
  outgoingFlows: number;
  /** The three most sensitive distinct data categories across this asset's flows. */
  topCategories: string[];
  /** How many more categories the system's flows carry beyond `topCategories`. */
  moreCategories: number;
  /** True when no recorded flow starts or ends at this system. */
  isIsolated: boolean;
  /** Highest-sensitivity class across this asset's flows. Drives the risk halo. */
  peakSensitivity: "special" | "sensitive" | "general" | "none";
  isHighlighted?: boolean;
  isDimmed?: boolean;
  isFocused?: boolean;
}

export interface FlowEdgeData extends Record<string, unknown> {
  flow: FlowData;
  label: string;
  isBidirectional: boolean;
  isReturn: boolean;
  isAutoGenerated: boolean;
  /** Position among flows joining the same two systems in the same direction (0-based). */
  parallelIndex: number;
  /** How many flows join the same two systems in the same direction. */
  parallelCount: number;
  isDimmed?: boolean;
  /** Opens the flow's details (the edge label is a button). */
  onSelect?: (flow: FlowData) => void;
}

export type AssetNode = Node<AssetNodeData>;
export type FlowEdge = Edge<FlowEdgeData>;

/** One transfer outside the EEA, as the server places it (see transfer-markers.ts). */
export interface OverlayTransferData {
  id: string;
  name: string;
  country: string;
  mechanism: string | null;
  status: TransferStatus;
  /** True when no status is recorded and `status` is the rules' suggestion. */
  suggested: boolean;
  assetIds: string[];
  vendorId: string | null;
}

/** A vendor that no system stands for. */
export interface OverlayVendorData {
  id: string;
  name: string;
  unrecordedCountries: string[];
}

export interface TransferLayerInput {
  transfers: OverlayTransferData[];
  vendors: OverlayVendorData[];
}

export interface VendorNodeData extends Record<string, unknown> {
  kind: "vendor";
  vendor: OverlayVendorData;
  isDimmed?: boolean;
}

export interface CountryNodeData extends Record<string, unknown> {
  kind: "country";
  country: string;
  transfers: OverlayTransferData[];
  worstStatus: TransferStatus;
  isDimmed?: boolean;
}

export type VendorNode = Node<VendorNodeData>;
export type CountryNode = Node<CountryNodeData>;
export type OverlayNode = VendorNode | CountryNode;

export interface TransferEdgeData extends Record<string, unknown> {
  transfer: OverlayTransferData;
  isDimmed?: boolean;
}
export type TransferEdge = Edge<TransferEdgeData>;

const STATUS_RANK: Record<TransferStatus, number> = {
  COMPLIANT: 0,
  PENDING: 1,
  NEEDS_REVIEW: 2,
  NON_COMPLIANT: 3,
};

/**
 * The transfer layer of the map: a node per destination country outside the
 * EEA, a node per vendor that no system stands for, and one edge per
 * transfer from where it starts (the system it is placed on, else its
 * vendor) to its country. A transfer with neither still counts on its
 * country node, so no transfer record is left out.
 *
 * In "asset" mode only the transfers placed on that system are drawn, and
 * no vendor nodes.
 */
export function buildTransferLayer(
  mode: "all" | "asset",
  assetId: string | undefined,
  /** The systems drawn on the map. */
  assetIds: ReadonlySet<string>,
  layer: TransferLayerInput | null | undefined
): { nodes: OverlayNode[]; edges: TransferEdge[] } {
  if (!layer) return { nodes: [], edges: [] };
  const focus = mode === "asset" && assetId ? assetId : null;
  const transfers = focus
    ? layer.transfers.filter((t) => t.assetIds.includes(focus))
    : layer.transfers;

  const vendorNodes: VendorNode[] = focus
    ? []
    : layer.vendors.map((v) => ({
        id: `vendor:${v.id}`,
        type: "vendorNode",
        position: { x: 0, y: 0 },
        data: { kind: "vendor", vendor: v },
      }));
  const vendorIds = new Set(vendorNodes.map((n) => n.data.vendor.id));

  const byCountry = new Map<string, OverlayTransferData[]>();
  const edges: TransferEdge[] = [];
  const seenEdge = new Set<string>();
  for (const t of transfers) {
    byCountry.set(t.country, [...(byCountry.get(t.country) ?? []), t]);
    const starts = t.assetIds.filter((id) => assetIds.has(id) && (!focus || id === focus));
    const sources =
      starts.length > 0
        ? starts
        : t.vendorId && vendorIds.has(t.vendorId)
          ? [`vendor:${t.vendorId}`]
          : [];
    for (const source of sources) {
      const id = `transfer:${t.id}:${source}`;
      if (seenEdge.has(id)) continue;
      seenEdge.add(id);
      edges.push({
        id,
        source,
        target: `country:${t.country}`,
        type: "transferEdge",
        data: { transfer: t },
      });
    }
  }

  const countryNodes: CountryNode[] = [...byCountry.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([country, list]) => ({
      id: `country:${country}`,
      type: "countryNode",
      position: { x: 0, y: 0 },
      data: {
        kind: "country",
        country,
        transfers: list,
        worstStatus: list.reduce<TransferStatus>(
          (w, t) => (STATUS_RANK[t.status] > STATUS_RANK[w] ? t.status : w),
          "COMPLIANT"
        ),
      },
    }));

  return { nodes: [...vendorNodes, ...countryNodes], edges };
}

const NODE_WIDTH = 240;
const NODE_HEIGHT = 120;

async function getLayoutedElements<N extends Node, E extends Edge>(
  nodes: N[],
  edges: E[],
  direction: "LR" | "TB" = "LR"
): Promise<{ nodes: N[]; edges: E[] }> {
  const elkDirection = direction === "LR" ? "RIGHT" : "DOWN";

  const graph = {
    id: "root",
    layoutOptions: {
      "elk.algorithm": "layered",
      "elk.direction": elkDirection,
      "elk.spacing.nodeNode": "60",
      "elk.layered.spacing.nodeNodeBetweenLayers": "120",
      "elk.layered.spacing.edgeNodeBetweenLayers": "40",
      "elk.padding": "[top=40,left=40,bottom=40,right=40]",
      "elk.layered.nodePlacement.strategy": "NETWORK_SIMPLEX",
      "elk.layered.crossingMinimization.strategy": "LAYER_SWEEP",
    },
    children: nodes.map((n) => ({
      id: n.id,
      width: NODE_WIDTH,
      height: NODE_HEIGHT,
    })),
    edges: edges.map((e) => ({
      id: e.id,
      sources: [e.source],
      targets: [e.target],
    })),
  };

  const layout = await elk.layout(graph);
  const positions = new Map<string, { x: number; y: number }>();
  for (const child of layout.children ?? []) {
    if (child.x != null && child.y != null) {
      positions.set(child.id, { x: child.x, y: child.y });
    }
  }

  const layoutedNodes = nodes.map((node) => {
    const pos = positions.get(node.id);
    return {
      ...node,
      position: pos ?? { x: 0, y: 0 },
    };
  });

  return { nodes: layoutedNodes, edges };
}

/** Counts that go with the drawn map. */
export interface GraphSummary {
  systems: number;
  isolatedSystems: number;
  flows: number;
  systemsWithTransfers: number;
  /** Transfers outside the EEA on the map, vendors drawn on their own, destination countries. */
  transfers: number;
  vendors: number;
  countries: number;
}

/**
 * The map's nodes and edges.
 *
 * - "all": every system of the organisation is a node, whether or not a
 *   flow touches it (a system with no flow still shows its transfer
 *   markers), plus any system at either end of a flow that the list given
 *   lacks (a paged or department-limited list).
 * - "asset": the system and its direct neighbours.
 *
 * Each system and each flow appears once (repeated ids are dropped); a flow
 * that starts and ends at the same system is not drawn. Flows that join the
 * same two systems in the same direction are numbered so the edges can be
 * drawn apart.
 */
export function buildNodesAndEdges(
  mode: "all" | "asset",
  assetId: string | undefined,
  assets: AssetData[],
  flows: FlowData[]
): { nodes: AssetNode[]; edges: FlowEdge[]; summary: GraphSummary } {
  // One entry per id, first one wins.
  const assetMap = new Map<string, AssetData>();
  for (const a of assets) if (!assetMap.has(a.id)) assetMap.set(a.id, a);
  const seenFlowIds = new Set<string>();
  const uniqueFlows: FlowData[] = [];
  for (const f of flows) {
    if (seenFlowIds.has(f.id)) continue;
    seenFlowIds.add(f.id);
    if (f.sourceAssetId === f.destinationAssetId) continue;
    uniqueFlows.push(f);
  }

  let relevantAssetIds: Set<string>;
  let relevantFlows: FlowData[];

  if (mode === "asset" && assetId) {
    relevantFlows = uniqueFlows.filter(
      (f) => f.sourceAssetId === assetId || f.destinationAssetId === assetId
    );
    relevantAssetIds = new Set<string>([assetId]);
    relevantFlows.forEach((f) => {
      relevantAssetIds.add(f.sourceAssetId);
      relevantAssetIds.add(f.destinationAssetId);
    });
  } else {
    relevantFlows = uniqueFlows;
    relevantAssetIds = new Set<string>(assetMap.keys());
    relevantFlows.forEach((f) => {
      relevantAssetIds.add(f.sourceAssetId);
      relevantAssetIds.add(f.destinationAssetId);
    });
  }

  // Every flow carries both of its ends, so a system missing from `assets`
  // still gets its node: an edge is never dropped for want of one.
  for (const f of relevantFlows) {
    if (!assetMap.has(f.sourceAssetId)) assetMap.set(f.sourceAssetId, f.sourceAsset);
    if (!assetMap.has(f.destinationAssetId)) assetMap.set(f.destinationAssetId, f.destinationAsset);
  }

  // Calculate flow counts + per-asset category aggregation
  const incomingFlowCounts = new Map<string, number>();
  const outgoingFlowCounts = new Map<string, number>();
  const assetCategories = new Map<string, Set<string>>();

  const addCategories = (id: string, categories: string[]) => {
    let set = assetCategories.get(id);
    if (!set) {
      set = new Set<string>();
      assetCategories.set(id, set);
    }
    for (const c of categories) set.add(c);
  };

  relevantFlows.forEach((flow) => {
    incomingFlowCounts.set(
      flow.destinationAssetId,
      (incomingFlowCounts.get(flow.destinationAssetId) || 0) + 1
    );
    outgoingFlowCounts.set(
      flow.sourceAssetId,
      (outgoingFlowCounts.get(flow.sourceAssetId) || 0) + 1
    );
    addCategories(flow.sourceAssetId, flow.dataCategories);
    addCategories(flow.destinationAssetId, flow.dataCategories);
  });

  // Create nodes
  const nodes: AssetNode[] = [];
  for (const id of relevantAssetIds) {
    const asset = assetMap.get(id);
    if (!asset) continue;

    const categories = [...(assetCategories.get(asset.id) ?? [])];
    const peakSensitivity = classifyCategories(categories);
    // The most sensitive first, so the chips agree with the risk halo.
    const ranked = categories
      .map((c, i) => ({ c, i }))
      .sort((x, y) => sensitivityRank(y.c) - sensitivityRank(x.c) || x.i - y.i)
      .map((x) => x.c);
    const incoming = incomingFlowCounts.get(asset.id) || 0;
    const outgoing = outgoingFlowCounts.get(asset.id) || 0;

    nodes.push({
      id: asset.id,
      type: "assetNode",
      position: { x: 0, y: 0 }, // Will be set by layout
      data: {
        label: asset.name,
        asset,
        incomingFlows: incoming,
        outgoingFlows: outgoing,
        topCategories: ranked.slice(0, 3),
        moreCategories: Math.max(0, ranked.length - 3),
        isIsolated: incoming + outgoing === 0,
        peakSensitivity,
        isHighlighted: false,
        isDimmed: false,
        isFocused: mode === "asset" && asset.id === assetId,
      },
    });
  }

  // Detect bidirectional pairs (A→B and B→A both exist), and number the
  // flows of each directed pair.
  const pairKeys = new Set<string>();
  const bidirectionalKeys = new Set<string>();
  const parallelTotals = new Map<string, number>();
  for (const flow of relevantFlows) {
    const fwd = `${flow.sourceAssetId}:${flow.destinationAssetId}`;
    const rev = `${flow.destinationAssetId}:${flow.sourceAssetId}`;
    if (pairKeys.has(rev)) {
      bidirectionalKeys.add(fwd);
      bidirectionalKeys.add(rev);
    }
    pairKeys.add(fwd);
    parallelTotals.set(fwd, (parallelTotals.get(fwd) ?? 0) + 1);
  }

  // Create edges, marking return edges for bidirectional pairs
  // The direction seen first in a two-way pair is the outward one; every
  // flow in the other direction is the return.
  const firstDirection = new Map<string, string>();
  const parallelSeen = new Map<string, number>();
  const edges: FlowEdge[] = relevantFlows.map((flow) => {
    const key = `${flow.sourceAssetId}:${flow.destinationAssetId}`;
    const pairId = [flow.sourceAssetId, flow.destinationAssetId].sort().join(":");
    if (!firstDirection.has(pairId)) firstDirection.set(pairId, key);
    const isBidirectional = bidirectionalKeys.has(key);
    const returnSide = isBidirectional && firstDirection.get(pairId) !== key;
    const parallelIndex = parallelSeen.get(key) ?? 0;
    parallelSeen.set(key, parallelIndex + 1);

    const meta = flow.metadata as { autoGenerated?: boolean } | null | undefined;
    const isAutoGenerated = meta?.autoGenerated === true;

    return {
      id: flow.id,
      source: flow.sourceAssetId,
      target: flow.destinationAssetId,
      type: "flowEdge",
      // Dashes mean "generated from an activity" (the AUTO-GEN filter); an
      // automated flow is said so in its details, not with moving dashes.
      animated: false,
      data: {
        flow,
        label: flow.name,
        isBidirectional,
        isReturn: returnSide,
        isAutoGenerated,
        parallelIndex,
        parallelCount: parallelTotals.get(key) ?? 1,
      },
    };
  });

  const summary: GraphSummary = {
    systems: nodes.length,
    isolatedSystems: nodes.filter((n) => n.data.isIsolated).length,
    flows: edges.length,
    systemsWithTransfers: nodes.filter(
      (n) =>
        (n.data.asset.transfersOutsideEea?.transferIds.length ?? 0) > 0 ||
        (n.data.asset.transfersOutsideEea?.unrecordedCountries?.length ?? 0) > 0
    ).length,
    transfers: 0,
    vendors: 0,
    countries: 0,
  };

  return { nodes, edges, summary };
}

interface UseDataFlowGraphOptions {
  mode: "all" | "asset";
  assetId?: string;
  assets: AssetData[];
  flows: FlowData[];
  /** Transfers outside the EEA and vendors without a system (country and vendor nodes). */
  transferLayer?: TransferLayerInput | null;
}

export function useDataFlowGraph({
  mode,
  assetId,
  assets,
  flows,
  transferLayer,
}: UseDataFlowGraphOptions) {
  const [layoutedNodes, setLayoutedNodes] = useState<AssetNode[]>([]);
  const [layoutedEdges, setLayoutedEdges] = useState<FlowEdge[]>([]);
  const [layoutedOverlayNodes, setLayoutedOverlayNodes] = useState<OverlayNode[]>([]);
  const [layoutedTransferEdges, setLayoutedTransferEdges] = useState<TransferEdge[]>([]);
  const [isLoading, setIsLoading] = useState(true);

  // Build initial nodes/edges without layout
  const { initialNodes, initialEdges, overlayNodes, transferEdges, summary } = useMemo(() => {
    const base = buildNodesAndEdges(mode, assetId, assets, flows);
    const layer = buildTransferLayer(mode, assetId, new Set(base.nodes.map((n) => n.id)), transferLayer);
    return {
      initialNodes: base.nodes,
      initialEdges: base.edges,
      overlayNodes: layer.nodes,
      transferEdges: layer.edges,
      summary: {
        ...base.summary,
        transfers: layer.nodes
          .filter((n): n is CountryNode => n.data.kind === "country")
          .reduce((sum, n) => sum + n.data.transfers.length, 0),
        vendors: layer.nodes.filter((n) => n.data.kind === "vendor").length,
        countries: layer.nodes.filter((n) => n.data.kind === "country").length,
      },
    };
  }, [mode, assetId, assets, flows, transferLayer]);

  // Apply ELK layout (async)
  useEffect(() => {
    let cancelled = false;

    if (initialNodes.length === 0 && overlayNodes.length === 0) {
      setLayoutedNodes([]);
      setLayoutedEdges([]);
      setLayoutedOverlayNodes([]);
      setLayoutedTransferEdges([]);
      setIsLoading(false);
      return;
    }

    const allNodes: Node[] = [...initialNodes, ...overlayNodes];
    const allEdges: Edge[] = [...initialEdges, ...transferEdges];
    const split = (laidOut: Node[]) => {
      const at = new Map(laidOut.map((n) => [n.id, n.position]));
      setLayoutedNodes(initialNodes.map((n) => ({ ...n, position: at.get(n.id) ?? n.position })));
      setLayoutedOverlayNodes(overlayNodes.map((n) => ({ ...n, position: at.get(n.id) ?? n.position }) as OverlayNode));
      setLayoutedEdges(initialEdges);
      setLayoutedTransferEdges(transferEdges);
    };

    setIsLoading(true);
    getLayoutedElements(allNodes, allEdges, "LR")
      .then(({ nodes: laidOutNodes }) => {
        if (cancelled) return;
        split(laidOutNodes);
      })
      .catch((error) => {
        console.error("Failed to layout graph:", error);
        if (cancelled) return;
        // Fallback to a simple grid layout
        split(
          allNodes.map((node, i) => ({
            ...node,
            position: {
              x: (i % 4) * (NODE_WIDTH + 80),
              y: Math.floor(i / 4) * (NODE_HEIGHT + 80),
            },
          }))
        );
      })
      .finally(() => {
        if (!cancelled) setIsLoading(false);
      });

    return () => {
      cancelled = true;
    };
  }, [initialNodes, initialEdges, overlayNodes, transferEdges]);

  return {
    nodes: layoutedNodes,
    edges: layoutedEdges,
    overlayNodes: layoutedOverlayNodes,
    transferEdges: layoutedTransferEdges,
    isLoading,
    summary,
  };
}
