/**
 * Words the data flow map shows, in the reader's language. A flow's frequency
 * is free text: the values the app writes are stored in English and shown
 * through `dataFlow.frequencyOptions`; anything else (text a person typed,
 * or a Spanish industry template's own words) is shown as written. Category
 * abbreviations come from `dataFlow.abbr`.
 */

/** Stored frequency values the app writes, and the message key that labels each. */
export const FREQUENCY_LABEL_KEYS: Record<string, string> = {
  "Real-time": "realTime",
  Hourly: "hourly",
  Daily: "daily",
  Weekly: "weekly",
  Monthly: "monthly",
  "On-demand": "onDemand",
  Batch: "batch",
  Continuous: "continuous",
  "On request": "onRequest",
};

type Translate = (key: string) => string;

/** A frequency in the reader's language (`t` reads `dataFlow.frequencyOptions`). */
export function frequencyLabel(frequency: string | null | undefined, t: Translate): string | null {
  if (!frequency) return null;
  const key = FREQUENCY_LABEL_KEYS[frequency];
  return key ? t(key) : frequency;
}

/**
 * The short label on an edge: the first category's abbreviation, "+N" for the
 * rest, then the frequency. `abbr` reads `dataFlow.abbr`, `freq` reads
 * `dataFlow.frequencyOptions`. Null when the flow has neither.
 */
export function edgeShortLabel(
  categories: string[] | null | undefined,
  frequency: string | null | undefined,
  abbr: Translate,
  freq: Translate
): string | null {
  const cats = categories ?? [];
  const head = cats.length > 0 ? abbr(cats[0]!) + (cats.length > 1 ? ` +${cats.length - 1}` : "") : null;
  const f = frequencyLabel(frequency, freq);
  if (head && f) return `${head} · ${f.toLowerCase()}`;
  return head ?? f;
}

/** True for a flow drawn from a processing activity's systems (edited or not). */
export function isGeneratedFlow(metadata: unknown): boolean {
  if (!metadata || typeof metadata !== "object") return false;
  const m = metadata as { autoGenerated?: boolean; editedFromGenerated?: boolean };
  return m.autoGenerated === true || m.editedFromGenerated === true;
}

/** The English description older releases stored on generated flows. */
export const LEGACY_GENERATED_DESCRIPTION = /^Auto-generated from processing activity "/;
