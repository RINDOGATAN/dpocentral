import { memo } from "react";
import { useTranslations } from "next-intl";
import {
  BaseEdge,
  EdgeLabelRenderer,
  getBezierPath,
  type EdgeProps,
  type Edge,
} from "@xyflow/react";
import type { FlowEdgeData } from "./useDataFlowGraph";
import {
  classifyCategories,
  SENSITIVITY_COLOR,
  strokeWidthForFrequency,
} from "./flow-palette";
import { edgeShortLabel } from "./flow-labels";

/** Vertical offset of the label of each direction of a two-way pair, so both stay readable. */
const PAIR_LABEL_OFFSET = 14;

type FlowEdgeProps = EdgeProps<Edge<FlowEdgeData>>;

function FlowEdgeComponent({
  id,
  sourceX,
  sourceY,
  targetX,
  targetY,
  sourcePosition,
  targetPosition,
  data,
  selected,
}: FlowEdgeProps) {
  const isReturn = data?.isReturn ?? false;
  const isBidirectional = data?.isBidirectional ?? false;
  const isAutoGenerated = data?.isAutoGenerated ?? false;
  const isDimmed = data?.isDimmed ?? false;
  const flow = data?.flow;
  const tAbbr = useTranslations("dataFlow.abbr");
  const tFreq = useTranslations("dataFlow.frequencyOptions");
  const tEdge = useTranslations("dataFlow.edge");

  const sensitivity = classifyCategories(flow?.dataCategories);
  const sColor = SENSITIVITY_COLOR[sensitivity];

  const baseWidth = strokeWidthForFrequency(flow?.frequency);
  const strokeWidth = selected ? baseWidth + 1.5 : baseWidth;

  // Flows joining the same two systems in the same direction bend further
  // apart one by one, so none hides another.
  const parallelIndex = data?.parallelIndex ?? 0;
  const spread = parallelIndex * 0.3;
  const curvature = isReturn ? 0.5 + spread : isBidirectional ? -0.5 - spread : 0.22 + spread;

  const [edgePath, labelX, labelY] = getBezierPath({
    sourceX,
    sourceY,
    sourcePosition,
    targetX,
    targetY,
    targetPosition,
    curvature,
  });

  // Dim rules — explicit (dim flag) beats everything; auto-generated is always subtle.
  const opacity = isDimmed ? 0.12 : selected ? 1 : isAutoGenerated ? 0.55 : 0.85;

  // Short label in the reader's language: abbreviated top category (+N) and
  // frequency; the flow's name when it has neither.
  const label =
    edgeShortLabel(
      flow?.dataCategories,
      flow?.frequency,
      (k) => (tAbbr.has(k as never) ? tAbbr(k as never) : k.slice(0, 3)),
      (k) => tFreq(k as never)
    ) ||
    flow?.name ||
    tEdge("fallback");
  // The two directions of a pair share a midpoint: lift one label, drop the other.
  const labelOffset =
    (isBidirectional ? (isReturn ? PAIR_LABEL_OFFSET : -PAIR_LABEL_OFFSET) : 0) +
    (isReturn ? 1 : -1) * parallelIndex * PAIR_LABEL_OFFSET;

  return (
    <>
      <BaseEdge
        id={id}
        path={edgePath}
        style={{
          stroke: sColor.stroke,
          strokeWidth,
          strokeDasharray: isAutoGenerated ? "4 3" : undefined,
          opacity,
          transition: "opacity 200ms, stroke-width 150ms",
        }}
        markerEnd={`url(#arrowhead-${sensitivity})`}
      />
      <EdgeLabelRenderer>
        <button
          type="button"
          onClick={(e) => {
            e.stopPropagation();
            if (flow) data?.onSelect?.(flow);
          }}
          aria-label={tEdge("open", { name: flow?.name ?? label })}
          className="nodrag nopan absolute flex items-center gap-1 px-2 py-0.5 text-[9px] font-semibold uppercase tracking-wider cursor-pointer transition-all duration-200 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring"
          style={{
            transform: `translate(-50%, -50%) translate(${labelX}px, ${labelY + labelOffset}px)`,
            pointerEvents: "all",
            opacity: isDimmed ? 0.15 : 1,
            backgroundColor: selected ? sColor.stroke : "#ffffff",
            color: selected ? "white" : sColor.fg,
            border: `1px solid ${selected ? sColor.stroke : sColor.bg}`,
            letterSpacing: "0.04em",
          }}
        >
          {label}
        </button>
      </EdgeLabelRenderer>
    </>
  );
}

export const FlowEdge = memo(FlowEdgeComponent);
