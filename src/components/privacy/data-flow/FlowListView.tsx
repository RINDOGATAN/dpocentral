/**
 * The data map as a list: every flow (source, destination, categories,
 * frequency, draft or confirmed) and every system with its transfers
 * outside the EEA, including systems no flow touches. The same records as
 * the canvas, readable by keyboard and screen reader and on a phone.
 */

import Link from "next/link";
import { useLocale, useTranslations } from "next-intl";
import { ArrowRight } from "lucide-react";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import type { AssetNode, CountryNode, FlowData, OverlayNode, VendorNode } from "./useDataFlowGraph";
import { countryName } from "@/lib/country-code";
import { TRANSFER_STATUS_COLOR } from "./flow-palette";
import { frequencyLabel } from "./flow-labels";

export function FlowListView({
  nodes,
  flows,
  overlay = [],
  onOpenFlow,
}: {
  nodes: AssetNode[];
  flows: FlowData[];
  /** Country and vendor nodes of the transfer layer. */
  overlay?: OverlayNode[];
  onOpenFlow: (flow: FlowData) => void;
}) {
  const locale = useLocale();
  const countries = overlay.filter((n): n is CountryNode => n.data.kind === "country");
  const vendors = overlay.filter((n): n is VendorNode => n.data.kind === "vendor");
  const t = useTranslations("dataFlow");
  const tCategory = useTranslations("enums.dataCategory");
  const tAssetType = useTranslations("pages.newAsset.assetType");
  const tMech = useTranslations("pages.dataInventory.mechanism");
  const tStatus = useTranslations("pages.transfers.status_option");

  const nameOf = new Map(nodes.map((n) => [n.id, n.data.asset.name]));
  const systems = [...nodes].sort((a, b) => a.data.asset.name.localeCompare(b.data.asset.name));

  return (
    <div className="space-y-4" data-testid="flow-list-view">
      <Card>
        <CardHeader className="pb-2">
          <CardTitle className="text-base">{t("list.flowsTitle", { count: flows.length })}</CardTitle>
        </CardHeader>
        <CardContent>
          {flows.length === 0 ? (
            <p className="text-sm text-muted-foreground">{t("empty.noFlowsHint")}</p>
          ) : (
            <ul className="divide-y">
              {flows.map((f) => {
                const draft = (f.metadata as { autoGenerated?: boolean } | null | undefined)?.autoGenerated === true;
                return (
                  <li key={f.id} className="py-2">
                    <button
                      type="button"
                      onClick={() => onOpenFlow(f)}
                      className="w-full text-left hover:bg-muted/40 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring p-1"
                    >
                      <span className="flex flex-wrap items-center gap-1.5 text-sm font-medium">
                        <span className="break-words">{nameOf.get(f.sourceAssetId) ?? f.sourceAsset.name}</span>
                        <ArrowRight className="w-3.5 h-3.5 shrink-0" aria-label={t("list.to")} />
                        <span className="break-words">{nameOf.get(f.destinationAssetId) ?? f.destinationAsset.name}</span>
                        {draft && (
                          <Badge variant="outline" className="text-[10px]">
                            {t("details.draftBadge")}
                          </Badge>
                        )}
                      </span>
                      <span className="block text-xs text-muted-foreground mt-0.5">
                        {f.dataCategories.length > 0
                          ? f.dataCategories
                              .map((c) => (tCategory.has(c as never) ? tCategory(c as never) : c))
                              .join(", ")
                          : t("details.noCategories")}
                        {f.frequency
                          ? ` · ${frequencyLabel(f.frequency, (k) => t(`frequencyOptions.${k}` as never))}`
                          : ""}
                      </span>
                    </button>
                  </li>
                );
              })}
            </ul>
          )}
        </CardContent>
      </Card>

      {countries.length > 0 && (
        <Card data-testid="flow-list-transfers">
          <CardHeader className="pb-2">
            <CardTitle className="text-base">
              {t("list.transfersTitle", { count: countries.reduce((n, c) => n + c.data.transfers.length, 0) })}
            </CardTitle>
          </CardHeader>
          <CardContent>
            <ul className="divide-y">
              {countries.map((c) => (
                <li key={c.id} className="py-2 text-sm">
                  <p className="font-medium">{countryName(c.data.country, locale)} ({c.data.country})</p>
                  <ul className="mt-1 space-y-1">
                    {c.data.transfers.map((tr) => (
                      <li key={tr.id} className="flex flex-wrap items-center gap-1.5 text-xs">
                        <Link href={`/privacy/transfers/${tr.id}`} className="hover:underline break-words">
                          {tr.name || tr.country}
                        </Link>
                        <span className="text-muted-foreground">
                          {tr.mechanism && tMech.has(tr.mechanism as never)
                            ? tMech(tr.mechanism as never)
                            : t("node.noMechanism")}
                        </span>
                        <span
                          className="text-[10px] font-bold uppercase tracking-wider px-1.5 py-0.5"
                          style={{
                            backgroundColor: TRANSFER_STATUS_COLOR[tr.status].bg,
                            color: TRANSFER_STATUS_COLOR[tr.status].fg,
                          }}
                        >
                          {tr.suggested
                            ? t("node.suggestedStatus", { status: tStatus(tr.status) })
                            : tStatus(tr.status)}
                        </span>
                      </li>
                    ))}
                  </ul>
                </li>
              ))}
            </ul>
          </CardContent>
        </Card>
      )}

      {vendors.length > 0 && (
        <Card data-testid="flow-list-vendors">
          <CardHeader className="pb-2">
            <CardTitle className="text-base">{t("list.vendorsTitle", { count: vendors.length })}</CardTitle>
          </CardHeader>
          <CardContent>
            <ul className="divide-y">
              {vendors.map((v) => (
                <li key={v.id} className="py-2 text-sm">
                  <Link href={`/privacy/vendors/${v.data.vendor.id}`} className="font-medium hover:underline break-words">
                    {v.data.vendor.name}
                  </Link>
                  {v.data.vendor.unrecordedCountries.length > 0 && (
                    <p className="mt-1 text-xs text-destructive">
                      {t("node.unrecorded", { countries: v.data.vendor.unrecordedCountries.join(", ") })}
                    </p>
                  )}
                </li>
              ))}
            </ul>
          </CardContent>
        </Card>
      )}

      <Card>
        <CardHeader className="pb-2">
          <CardTitle className="text-base">{t("list.systemsTitle", { count: systems.length })}</CardTitle>
        </CardHeader>
        <CardContent>
          <ul className="divide-y">
            {systems.map((n) => {
              const a = n.data.asset;
              const m = a.transfersOutsideEea;
              return (
                <li key={n.id} className="py-2 text-sm">
                  <div className="flex flex-wrap items-center gap-1.5">
                    <Link href={`/privacy/data-inventory/${a.id}`} className="font-medium hover:underline break-words">
                      {a.name}
                    </Link>
                    <span className="text-xs text-muted-foreground">{tAssetType(a.type)}</span>
                    {n.data.isIsolated && (
                      <Badge variant="outline" className="text-[10px]">
                        {t("node.noFlows")}
                      </Badge>
                    )}
                  </div>
                  {!n.data.isIsolated && (
                    <p className="text-xs text-muted-foreground">
                      {t("list.flowCounts", { inbound: n.data.incomingFlows, outbound: n.data.outgoingFlows })}
                    </p>
                  )}
                  {(m?.transfers ?? []).length > 0 && (
                    <ul className="mt-1 space-y-1">
                      {(m?.transfers ?? []).map((tr) => (
                        <li key={tr.id} className="flex flex-wrap items-center gap-1.5 text-xs">
                          <Link href={`/privacy/transfers/${tr.id}`} className="hover:underline">
                            {t("node.outsideEea", { countries: tr.country })}
                          </Link>
                          <span className="text-muted-foreground">
                            {tr.mechanism && tMech.has(tr.mechanism as never)
                              ? tMech(tr.mechanism as never)
                              : t("node.noMechanism")}
                          </span>
                          <span
                            className="text-[10px] font-bold uppercase tracking-wider px-1.5 py-0.5"
                            style={{
                              backgroundColor: TRANSFER_STATUS_COLOR[tr.status].bg,
                              color: TRANSFER_STATUS_COLOR[tr.status].fg,
                            }}
                          >
                            {tr.suggested
                              ? t("node.suggestedStatus", { status: tStatus(tr.status) })
                              : tStatus(tr.status)}
                          </span>
                        </li>
                      ))}
                    </ul>
                  )}
                  {(m?.unrecordedCountries ?? []).length > 0 && (
                    <p className="mt-1 text-xs text-destructive">
                      <Link href="/privacy/transfers" className="hover:underline">
                        {t("node.unrecorded", { countries: (m?.unrecordedCountries ?? []).join(", ") })}
                      </Link>
                    </p>
                  )}
                </li>
              );
            })}
          </ul>
        </CardContent>
      </Card>
    </div>
  );
}
