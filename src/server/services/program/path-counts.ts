/**
 * The counts the privacy program path reads (src/components/guided/path-config.ts).
 *
 * Counts only, every one scoped to the organisation, all issued at once: no
 * record leaves the database, so the menu stays cheap to fill in. The rules
 * that turn these numbers into "done / started / not started" live next to
 * each step in the path config, not here.
 */

import type { Db } from "@/lib/prisma";
import type { PathCounts } from "@/components/guided/path-config";
import { isIntakeConfigured } from "@/server/services/dsar/defaultIntakeForm";
import { DRAFT_WHERE } from "@/server/services/template-items/drafts";
import { DRAFT_PROVENANCES } from "@/lib/drafts";
import {
  closestMissing,
  missingMinimumFields,
  missingVendorFields,
} from "@/lib/record-completeness";

/** How many confirmed records are read to find the minimum fields (rows read, never returned). */
const COMPLETENESS_SCAN = 500;

/** The risk assessments the "Assessments" step counts. */
const RISK_TYPES = ["DPIA", "PIA"] as const;

/**
 * A transfer is a draft while the record it hangs off is: its processing
 * activity or, when it has none, its vendor (the transfer to TODO.LAW,
 * src/server/services/todolaw-processor.ts).
 */
const TRANSFER_ON_DRAFT = {
  OR: [{ processingActivity: DRAFT_WHERE }, { processingActivityId: null, vendor: DRAFT_WHERE }],
};

/** Recorded compliance statuses ("PENDING" is not a recorded assessment). */
const RECORDED_TRANSFER_STATUS = ["COMPLIANT", "NEEDS_REVIEW", "NON_COMPLIANT"];

/**
 * A draft the quick start made on its own (metadata.autoGenerated) that nobody
 * has answered or moved on yet: not a sign that the step was started.
 */
const UNTOUCHED_AUTO_DRAFT = {
  status: "DRAFT" as const,
  metadata: { path: ["autoGenerated"], equals: true },
  responses: { none: {} },
};

function settingsObject(value: unknown): Record<string, unknown> {
  return value && typeof value === "object" && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : {};
}

export async function loadPathCounts(
  prisma: Db,
  organizationId: string,
): Promise<PathCounts> {
  const org = { organizationId };
  // A draft: created by the quick start, a template or another client's copy,
  // and not yet confirmed by a person (services/template-items/drafts.ts).
  const drafts = { organizationId, ...DRAFT_WHERE };
  // Confirmed: not a draft (entered by a person, or a draft a person confirmed).
  const confirmedRecords = {
    organizationId,
    OR: [{ provenance: { notIn: [...DRAFT_PROVENANCES] } }, { confirmedAt: { not: null } }],
  };
  const riskType = { template: { type: { in: [...RISK_TYPES] } } };
  const vendorType = { template: { type: "VENDOR" as const } };

  const [
    organization,
    dataAssets,
    dataAssetsDrafts,
    processingActivities,
    processingActivitiesDrafts,
    jurisdictions,
    vendors,
    vendorsDrafts,
    vendorsAssessed,
    vendorAssessments,
    assessments,
    assessmentsApproved,
    liaAssessments,
    liaApproved,
    transfers,
    transfersDrafts,
    dsarRequests,
    intakeForm,
    incidents,
    aiSystems,
    dataAssetsComplete,
    activityRows,
    vendorRows,
    riskAutoDrafts,
    vendorAutoDrafts,
    transfersRecorded,
    transfersRecordedOnDrafts,
  ] = await Promise.all([
    prisma.organization.findFirst({ where: { id: organizationId }, select: { settings: true } }),
    prisma.dataAsset.count({ where: org }),
    prisma.dataAsset.count({ where: drafts }),
    prisma.processingActivity.count({ where: org }),
    prisma.processingActivity.count({ where: drafts }),
    prisma.organizationJurisdiction.count({ where: org }),
    prisma.vendor.count({ where: org }),
    prisma.vendor.count({ where: drafts }),
    prisma.vendor.count({ where: { ...org, assessments: { some: { status: "APPROVED", ...vendorType } } } }),
    prisma.assessment.count({ where: { ...org, ...vendorType } }),
    prisma.assessment.count({ where: { ...org, ...riskType } }),
    prisma.assessment.count({ where: { ...org, status: "APPROVED", ...riskType } }),
    prisma.assessment.count({ where: { ...org, template: { type: "LIA" } } }),
    prisma.assessment.count({ where: { ...org, status: "APPROVED", template: { type: "LIA" } } }),
    prisma.dataTransfer.count({ where: org }),
    prisma.dataTransfer.count({ where: { ...org, ...TRANSFER_ON_DRAFT } }),
    prisma.dSARRequest.count({ where: org }),
    // The active intake form's shape, not just its presence: every org is
    // auto-seeded a default form so the public portal works out of the box, so
    // the mere existence of a form is no signal. We read its fields and decide
    // whether the org has actually set up its intake (isIntakeConfigured).
    prisma.dSARIntakeForm.findFirst({
      where: { ...org, isActive: true },
      select: {
        slug: true,
        title: true,
        description: true,
        thankYouMessage: true,
        privacyNoticeUrl: true,
        customCss: true,
        fields: true,
      },
    }),
    prisma.incident.count({ where: { ...org, recordedInErrorAt: null } }),
    // The AI systems table is optional on some deployments (the quick start
    // guards its creation the same way); an unreadable table counts as none.
    prisma.aISystem.count({ where: org }).catch(() => 0),
    prisma.dataAsset.count({ where: { ...confirmedRecords, dataElements: { some: {} } } }),
    prisma.processingActivity.findMany({
      where: confirmedRecords,
      select: { dataSubjects: true, categories: true, retentionPeriod: true, retentionDays: true },
      take: COMPLETENESS_SCAN,
    }),
    prisma.vendor.findMany({
      where: confirmedRecords,
      select: { status: true, dataProcessed: true, countries: true },
      take: COMPLETENESS_SCAN,
    }),
    prisma.assessment.count({ where: { ...org, ...riskType, ...UNTOUCHED_AUTO_DRAFT } }),
    prisma.assessment.count({ where: { ...org, ...vendorType, ...UNTOUCHED_AUTO_DRAFT } }),
    prisma.dataTransfer.count({ where: { ...org, complianceStatus: { in: RECORDED_TRANSFER_STATUS } } }),
    prisma.dataTransfer.count({
      where: { ...org, complianceStatus: { in: RECORDED_TRANSFER_STATUS }, ...TRANSFER_ON_DRAFT },
    }),
  ]);

  const activityMissing = activityRows.map((r) => missingMinimumFields(r));
  const vendorMissing = vendorRows.map((r) => missingVendorFields(r));
  const processingActivitiesComplete = activityMissing.filter((m) => m.length === 0).length;
  const vendorsComplete = vendorMissing.filter((m) => m.length === 0).length;
  const transfersComplete = Math.max(0, transfersRecorded - transfersRecordedOnDrafts);
  const confirmedAssets = Math.max(0, dataAssets - dataAssetsDrafts);
  const missing: NonNullable<PathCounts["missing"]> = {};
  if (processingActivitiesComplete === 0 && activityMissing.length > 0) missing.ropa = closestMissing(activityMissing);
  if (vendorsComplete === 0 && vendorMissing.length > 0) missing.vendors = closestMissing(vendorMissing);
  if (dataAssetsComplete === 0 && confirmedAssets > 0) missing.dataInventory = ["dataElements"];
  if (transfersComplete === 0 && transfers - transfersDrafts > 0) missing.transfers = ["complianceStatus"];

  const settings = settingsObject(organization?.settings);
  const quickstart = settingsObject(settings.quickstart);

  return {
    quickstartCompleted: typeof quickstart.completedAt === "string",
    dataAssets,
    dataAssetsDrafts,
    dataAssetsComplete,
    processingActivities,
    processingActivitiesDrafts,
    processingActivitiesComplete,
    jurisdictions,
    vendors,
    vendorsDrafts,
    vendorsComplete,
    vendorsAssessed,
    vendorAssessments: Math.max(0, vendorAssessments - vendorAutoDrafts),
    assessments: Math.max(0, assessments - riskAutoDrafts),
    assessmentsApproved,
    liaAssessments,
    liaApproved,
    transfers,
    transfersDrafts,
    transfersComplete,
    dsarRequests,
    dsarIntakeConfigured: intakeForm ? isIntakeConfigured(intakeForm) : false,
    incidents,
    aiSystems,
    boardReportsSaved: Object.keys(settingsObject(settingsObject(settings.boardReport).reports)).length,
    missing,
  };
}

/** Records drafted and not yet confirmed, across the three kinds. */
export function draftTotal(counts: PathCounts): number {
  return counts.dataAssetsDrafts + counts.processingActivitiesDrafts + counts.vendorsDrafts;
}
